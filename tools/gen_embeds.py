from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "autogenerated"
OUT.mkdir(parents=True, exist_ok=True)

def embed(path: Path, var: str, f) -> None:
    data = path.read_bytes()
    f.write(f"static char {var}[] = {{")
    f.write(",".join(f"0x{b:X}" for b in data))
    f.write(",0};\n")

with (OUT / "Embeds.hpp").open("w", encoding="utf-8") as f:
    f.write("#pragma once\n")
    embed(ROOT / "src/graphics/ff.vert", "vertShaderBytes", f)
    embed(ROOT / "src/graphics/ff.frag", "fragShaderBytes", f)

print("Embeds.hpp generated")
